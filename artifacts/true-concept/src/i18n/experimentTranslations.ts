/**
 * Resolve an experiment field for the active language.
 *
 * - In English mode: returns the Firestore source string unchanged.
 * - In Assamese mode: returns the overlay string if present, otherwise falls
 *   back to the Firestore source so a stub never blanks the UI.
 */
export function pickExpField(
  en: string | undefined | null,
  translation: ExperimentAsTranslation | undefined,
  field: keyof ExperimentAsTranslation,
  lang: Lang,
): string {
  const enStr = en ?? "";
  if (lang === "en") return enStr;
  const asStr = translation?.[field];
  return asStr && asStr.length > 0 ? asStr : enStr;
}
